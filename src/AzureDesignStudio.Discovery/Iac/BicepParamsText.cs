using System.Text;
using System.Text.Json;

namespace AzureDesignStudio.Discovery.Iac;

/// <summary>One parameter row of a .bicepparam contract; <see cref="IsSecret"/> follows secureString/secureObject.</summary>
public sealed record BicepParameter(string Name, string Type, bool IsSecret = false, bool Required = true);

/// <summary>Where secret values live at deploy time.</summary>
public sealed record KeyVaultPointer(string VaultName, string? SubscriptionId = null, string? ResourceGroup = null);

/// <summary>
/// Typed <c>.bicepparam</c> text (v2 plan 10.3) with the hard secret rule: secure parameters
/// are emitted as Key Vault references only - a plaintext secret value supplied by any caller
/// is dropped on the floor and said so in the file. Missing required values are flagged with
/// comments so validate-before-show (ArmTemplateValidator / bicep) catches them, never a
/// silent placeholder that deploys the wrong thing.
/// </summary>
public static class BicepParamsText
{
    public static string Generate(
        string usingPath,
        IEnumerable<BicepParameter> parameters,
        KeyVaultPointer? vault = null,
        IReadOnlyDictionary<string, string>? values = null)
    {
        var sb = new StringBuilder();
        sb.Append("// Generated by Azure Design Studio - parameter values for ").Append(usingPath).Append(".\n");
        sb.Append("// Secret parameters resolve from Key Vault at deploy time; plaintext secrets never land in this file.\n\n");
        sb.Append("using '").Append(usingPath.Replace("'", "\\'")).Append("'\n\n");

        foreach (var parameter in parameters)
        {
            if (parameter.IsSecret)
            {
                if (values is not null && values.ContainsKey(parameter.Name))
                    sb.Append("// Plaintext value for secret parameter '").Append(parameter.Name)
                      .Append("' was supplied and ignored by design - Key Vault reference only.\n");
                if (vault is null)
                {
                    sb.Append("// MISSING KEY VAULT for secret parameter '").Append(parameter.Name)
                      .Append("' - choose a vault before preview/deploy.\n\n");
                    continue;
                }
                sb.Append("param ").Append(parameter.Name).Append(" = {\n  keyVault: {\n");
                sb.Append("    name: '").Append(vault.VaultName.Replace("'", "\\'")).Append("'\n");
                sb.Append("    secretName: 'ads-").Append(SecretSlug(parameter.Name)).Append("'\n");
                if (vault.SubscriptionId is { Length: > 0 } sub)
                    sb.Append("    vaultSubscriptionId: '").Append(sub.Replace("'", "\\'")).Append("'\n");
                if (vault.ResourceGroup is { Length: > 0 } rg)
                    sb.Append("    vaultResourceGroupName: '").Append(rg.Replace("'", "\\'")).Append("'\n");
                sb.Append("  }\n}\n\n");
                continue;
            }

            if (values is null || !values.TryGetValue(parameter.Name, out var value))
            {
                if (parameter.Required)
                    sb.Append("// MISSING VALUE for required parameter '").Append(parameter.Name)
                      .Append("' - set it before preview/deploy.\n\n");
                continue; // optional without value: bicep default applies
            }

            sb.Append("param ").Append(parameter.Name).Append(" = ").Append(Literal(value, parameter.Type)).Append('\n').Append('\n');
        }

        return sb.ToString();
    }

    /// <summary>Bicep literals are typed: bool/int/array/object native, everything else a quoted string. Never throws.</summary>
    private static string Literal(string value, string type) => type.ToLowerInvariant() switch
    {
        "bool" when bool.TryParse(value, out var b) => b ? "true" : "false",
        "int" when long.TryParse(value, out _) => value,
        "object" or "array" when IsValidJson(value) => value,
        _ => "'" + value.Replace("\\", "\\\\").Replace("'", "\\'").Replace("\n", "\\n") + "'",
    };

    private static bool IsValidJson(string value)
    {
        try { JsonDocument.Parse(value).Dispose(); return true; } catch (JsonException) { return false; }
    }

    private static string SecretSlug(string name)
    {
        var sb = new StringBuilder(name.Length);
        foreach (var c in name)
            if (char.IsLetterOrDigit(c) || c is '-' or '_') sb.Append(char.ToLowerInvariant(c));
            else if (sb.Length > 0 && sb[^1] != '-') sb.Append('-');
        return sb.ToString().Trim('-');
    }
}
