using System.Linq;
using System.Text;
using System.Text.Json;
using AzureDesignStudio.Discovery.Inventory;

namespace AzureDesignStudio.Discovery.Iac;

/// <summary>
/// Terraform text from a scanned inventory (v2 plan 10.2 first cut), mirroring aztfexport's
/// honest split: with no per-type version table every resource is emitted as a generic
/// <c>azapi_resource</c> carrying the recorded live properties - a reviewable STARTING
/// POINT, never a silently-"correct" config. Deterministic: same scan, byte-identical
/// output (items id-sorted, body keys canonically sorted, collision suffixes in id order).
/// Dependency wiring and native azurerm resources are deliberate follow-ups, said so in the header.
/// </summary>
public static class TerraformText
{
    /// <summary>azapi resource types need an api-version; typeless scans don't carry one.</summary>
    public const string DefaultApiVersion = "2023-07-01";

    private static readonly JsonSerializerOptions JsonOptions = new();

    public static string Generate(IEnumerable<InventoryItem> items, string? asOfUtc = null, string apiVersion = DefaultApiVersion)
    {
        var ordered = items
            .Where(i => !string.IsNullOrEmpty(i.Id) && !string.IsNullOrEmpty(i.Type))
            .OrderBy(i => i.Id, StringComparer.Ordinal)
            .ToList();

        var exportable = ordered.Where(IsExportable).ToList();
        var skipped = ordered.Where(i => !IsExportable(i)).ToList();

        var sb = new StringBuilder();
        sb.Append("# Generated by Azure Design Studio from a live scan").Append(asOfUtc is null ? "." : $" (as of {asOfUtc}).").Append('\n');
        sb.Append("# STARTING POINT, NOT a reviewed configuration:\n");
        sb.Append("#   * every resource is a generic azapi_resource with the properties recorded at scan time\n");
        sb.Append($"#   * api-version {apiVersion} applied uniformly - pin real per-type versions before applying\n");
        sb.Append("#   * no dependency graph, no secrets, no computed state; `terraform plan` will show drift\n");
        if (skipped.Count > 0)
            sb.Append("#   * skipped (platform/subscription-level, not azapi-exportable):\n")
              .Append(string.Concat(skipped.Select(s => $"#       {s.Id}\n")));
        sb.Append('\n');

        sb.Append("""
            terraform {
              required_providers {
                azapi = {
                  source = "Azure/azapi"
                }
              }
            }

            provider "azapi" {
            }

            """);

        foreach (var (item, localName) in LocalNames(exportable))
            AppendResource(sb, item, localName, apiVersion);

        return sb.ToString();
    }

    /// <summary>Subscription containers themselves are terraform scope, not azapi resources.</summary>
    private static bool IsExportable(InventoryItem item) =>
        !item.Type.StartsWith("microsoft.resources/subscriptions", StringComparison.OrdinalIgnoreCase);

    private static void AppendResource(StringBuilder sb, InventoryItem item, string localName, string apiVersion)
    {
        sb.Append("resource \"azapi_resource\" \"").Append(localName).Append("\" {\n");
        sb.Append("  type      = \"").Append(EscapeHcl(item.Type)).Append('@').Append(apiVersion).Append("\"\n");
        sb.Append("  name      = \"").Append(EscapeHcl(item.Name)).Append("\"\n");
        sb.Append("  parent_id = \"").Append(EscapeHcl(ParentScope(item))).Append("\"\n");
        if (!string.IsNullOrEmpty(item.Location))
            sb.Append("  location  = \"").Append(EscapeHcl(item.Location)).Append("\"\n");

        if (item.Raw is { } raw && raw.ValueKind == JsonValueKind.Object && raw.EnumerateObject().Any())
        {
            sb.Append("  body = jsonencode(");
            AppendCanonicalJson(sb, raw, indent: 2);
            sb.Append(")\n");
        }

        if (item.Tags.Count > 0)
        {
            sb.Append("  tags = {\n");
            foreach (var tag in item.Tags.OrderBy(t => t.Key, StringComparer.Ordinal))
                sb.Append("    \"").Append(EscapeHcl(tag.Key)).Append("\" = \"").Append(EscapeHcl(tag.Value)).Append("\"\n");
            sb.Append("  }\n");
        }

        sb.Append("}\n\n");
    }

    /// <summary>TF local names: type+name, sanitized; collisions resolved with suffixes in id order.</summary>
    private static IEnumerable<(InventoryItem Item, string LocalName)> LocalNames(List<InventoryItem> ordered)
    {
        var used = new HashSet<string>(StringComparer.Ordinal);
        foreach (var item in ordered)
        {
            var baseName = Sanitize($"{item.ResourceTypeSegment.Replace('/', '_')}_{item.Name}");
            var name = baseName;
            for (var n = 2; !used.Add(name); n++)
                name = $"{baseName}_{n}";
            yield return (item, name);
        }
    }

    /// <summary>Nested: drop the last two ARM id segments (child type + name). Top-level: the scope before /providers/.</summary>
    private static string ParentScope(InventoryItem item)
    {
        if (item.Type.Count(c => c == '/') > 1)
        {
            var i = item.Id.LastIndexOf('/');
            var j = i > 0 ? item.Id.LastIndexOf('/', i - 1) : -1;
            if (j > 0) return item.Id[..j];
        }
        var p = item.Id.IndexOf("/providers/", StringComparison.OrdinalIgnoreCase);
        return p > 0 ? item.Id[..p] : ResourceGroupScope(item);
    }

    private static string ResourceGroupScope(InventoryItem item) =>
        $"/subscriptions/{item.SubscriptionId}/resourceGroups/{item.ResourceGroup}";

    /// <summary>
    /// Canonical JSON: object keys sorted ordinal (scan row order must not change the text),
    /// arrays keep order. JSON literals are valid HCL; Terraform template markers are
    /// neutralized so live values can never inject interpolation or directives into the .tf.
    /// </summary>
    private static void AppendCanonicalJson(StringBuilder sb, JsonElement element, int indent)
    {
        switch (element.ValueKind)
        {
            case JsonValueKind.Object when element.EnumerateObject().Any():
                sb.Append("{\n");
                foreach (var prop in element.EnumerateObject().OrderBy(p => p.Name, StringComparer.Ordinal))
                {
                    sb.Append(new string(' ', indent * 2)).Append(EscapeMarkers(JsonSerializer.Serialize(prop.Name, JsonOptions))).Append(": ");
                    AppendCanonicalJson(sb, prop.Value, indent + 1);
                    sb.Append(",\n");
                }
                sb.Append(new string(' ', (indent - 1) * 2)).Append('}');
                break;
            case JsonValueKind.Array when element.GetArrayLength() > 0:
                sb.Append("[\n");
                foreach (var item in element.EnumerateArray())
                {
                    sb.Append(new string(' ', indent * 2));
                    AppendCanonicalJson(sb, item, indent + 1);
                    sb.Append(",\n");
                }
                sb.Append(new string(' ', (indent - 1) * 2)).Append(']');
                break;
            default:
                sb.Append(EscapeMarkers(element.GetRawText())); // scalars + empty containers: JSON text is HCL-valid
                break;
        }
    }

    /// <summary>Neutralize Terraform template markers in already-encoded JSON text (quotes/backslashes are JSON-escaped already).</summary>
    private static string EscapeMarkers(string jsonText) => jsonText.Replace("${", "$${").Replace("%{", "%%{");

    /// <summary>HCL string escaping: quotes/backslashes, then Terraform marker neutralization.</summary>
    private static string EscapeHcl(string text) => EscapeMarkers(text
        .Replace("\\", "\\\\")
        .Replace("\"", "\\\""));

    private static string Sanitize(string name)
    {
        var sb = new StringBuilder(name.Length + 2);
        foreach (var c in name.ToLowerInvariant())
            sb.Append(char.IsAsciiLetterLower(c) || char.IsAsciiDigit(c) ? c : '_');
        var text = sb.ToString().Trim('_');
        return text.Length == 0 || char.IsAsciiDigit(text[0]) ? "r_" + text : text;
    }
}
