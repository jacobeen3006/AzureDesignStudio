using System.Globalization;
using System.Net;
using System.Text;

namespace AzureDesignStudio.Discovery.Report;

/// <summary>
/// Self-contained HTML for the static bundle (v2 plan 9.6): inline CSS, no scripts,
/// no external assets - the file survives email, SharePoint and `file://` unchanged.
/// Same model in, byte-identical document out (no clocks, no GUIDs, fixed order).
/// </summary>
public static class ReportHtml
{
    private const string Css = """
        body{font:14px/1.5 "Segoe UI",system-ui,sans-serif;margin:2rem auto;max-width:68rem;color:#1b1b1b}
        h1{font-size:1.4rem}h2{font-size:1.1rem;margin-top:2rem;border-bottom:1px solid #ddd;padding-bottom:.25rem}
        table{border-collapse:collapse;width:100%;margin:.5rem 0}
        th,td{border:1px solid #ddd;padding:.35rem .5rem;text-align:left;vertical-align:top}
        th{background:#f4f4f4}.num{text-align:right;white-space:nowrap}
        .sev-Critical{color:#c00;font-weight:600}.sev-High{color:#c60;font-weight:600}
        .sev-Medium{color:#660}.sev-Low{color:#066}
        footer{margin-top:2rem;color:#666;font-size:.85rem}
        code{font-family:Consolas,monospace;font-size:.9em;word-break:break-all}
        """;

    public static string Render(ReportModel model)
    {
        var sb = new StringBuilder();
        sb.Append("<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\"><title>")
            .Append(E(model.Title)).Append("</title><style>").Append(Css).Append("</style></head><body>");

        sb.Append("<h1>").Append(E(model.Title)).Append("</h1>");
        sb.Append("<p>Scope: <code>").Append(E(model.Scope)).Append("</code> &middot; As of ")
            .Append(E(Stamp(model.AsOf))).Append(" UTC</p>");

        Summary(sb, model);
        Exposure(sb, model);
        Unmanaged(sb, model);
        Drift(sb, model);
        Spend(sb, model);
        Topology(sb, model);

        sb.Append("<footer>Generated by Azure Design Studio. All figures reflect the scope and window recorded above.</footer>");
        sb.Append("</body></html>");
        return sb.ToString();
    }

    private static void Summary(StringBuilder sb, ReportModel m)
    {
        sb.Append("<h2>Summary</h2><table><tr><th>Section</th><th class=\"num\">Count</th></tr>");
        Row(sb, "Exposure findings", m.ExposureCount);
        Row(sb, "Unmanaged resources", m.UnmanagedCount);
        Row(sb, "Protected resources", m.ProtectedCount);
        Row(sb, "Drifted resources", m.DriftCount);
        if (m.SpendTotal is { } total)
            sb.Append("<tr><td>Actual spend</td><td class=\"num\">")
                .Append(E(Num(total)))
                .Append(' ').Append(E(m.SpendProvenance?.Currency ?? "")).Append("</td></tr>");
        sb.Append("</table>");
    }

    private static void Exposure(StringBuilder sb, ReportModel m)
    {
        if (m.Exposure is not { Count: > 0 } findings) return;
        sb.Append("<h2>Exposure</h2><table><tr><th>Severity</th><th>Kind</th><th>Resource</th><th>Detail</th><th>Remediation</th></tr>");
        foreach (var f in findings)
        {
            sb.Append("<tr><td class=\"sev-").Append(f.Severity).Append("\">").Append(f.Severity).Append("</td><td>")
                .Append(E(f.Kind)).Append("</td><td><code>").Append(E(f.ResourceId)).Append("</code></td><td>")
                .Append(E(f.Detail)).Append("</td><td>").Append(E(f.Remediation)).Append("</td></tr>");
        }
        sb.Append("</table>");
    }

    private static void Unmanaged(StringBuilder sb, ReportModel m)
    {
        if (m.Unmanaged is null) return;
        AppendFindings(sb, "Unmanaged resources", m.Unmanaged.Unmanaged);
        AppendFindings(sb, "Protected (do-not-touch)", m.Unmanaged.ProtectedResources);
    }

    private static void AppendFindings(StringBuilder sb, string title, IReadOnlyList<Unmanaged.ManagementFinding> items)
    {
        if (items.Count == 0) return;
        sb.Append("<h2>").Append(E(title)).Append("</h2><table><tr><th>Resource</th><th>Type</th><th>Reason</th></tr>");
        foreach (var f in items)
            sb.Append("<tr><td><code>").Append(E(f.Id)).Append("</code></td><td>").Append(E(f.Type))
                .Append("</td><td>").Append(E(f.Reason)).Append("</td></tr>");
        sb.Append("</table>");
    }

    private static void Drift(StringBuilder sb, ReportModel m)
    {
        if (m.Drift is not { Count: > 0 } items) return;
        sb.Append("<h2>Drift since scan</h2><table><tr><th>Status</th><th>Resource</th><th>Changed at</th><th>By</th><th>Operation</th></tr>");
        foreach (var d in items)
            sb.Append("<tr><td>").Append(d.Status).Append("</td><td><code>").Append(E(d.ResourceId))
                .Append("</code></td><td>").Append(E(Stamp(d.ChangedAt))).Append("</td><td>")
                .Append(E(d.ChangedBy ?? d.ClientType ?? "")).Append("</td><td>")
                .Append(E(d.Operation ?? "")).Append("</td></tr>");
        sb.Append("</table>");
    }

    private static void Spend(StringBuilder sb, ReportModel m)
    {
        if (m.SpendByServiceFamily is not { Count: > 0 } buckets) return;
        sb.Append("<h2>Spend by service family</h2><table><tr><th>Service family</th><th class=\"num\">Cost</th><th class=\"num\">Share</th></tr>");
        foreach (var b in buckets)
            sb.Append("<tr><td>").Append(E(b.Key)).Append("</td><td class=\"num\">").Append(E(Num(b.Cost)))
                .Append("</td><td class=\"num\">").Append(E(b.Share.ToString("P1", CultureInfo.InvariantCulture)))
                .Append("</td></tr>");
        sb.Append("</table>");

        if (m.SpendProvenance is { } p)
            sb.Append("<p><small>Source: ").Append(E(p.Source)).Append(" &middot; scope <code>").Append(E(p.Scope))
                .Append("</code> &middot; region ").Append(E(p.Region))
                .Append(" &middot; currency ").Append(E(p.Currency))
                .Append(" &middot; window ").Append(E(Stamp(p.From))).Append(" \u2192 ").Append(E(Stamp(p.To)))
                .Append(" &middot; fetched ").Append(E(Stamp(p.AsOf))).Append(" UTC</small></p>");
    }

    private static void Topology(StringBuilder sb, ReportModel m)
    {
        if (!ReportBundle.SafeSvg(m.TopologySvg)) return;
        sb.Append("<h2>Topology</h2>").Append(m.TopologySvg); // generated SVG (script-shaped content rejected), emitted verbatim
    }

    private static void Row(StringBuilder sb, string label, int count) =>
        sb.Append("<tr><td>").Append(E(label)).Append("</td><td class=\"num\">")
            .Append(count.ToString(CultureInfo.InvariantCulture)).Append("</td></tr>");

    private static string Num(decimal value) => value.ToString("0.00", CultureInfo.InvariantCulture);

    private static string Stamp(DateTimeOffset t) => t.ToUniversalTime().ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture);

    private static string E(string text) => WebUtility.HtmlEncode(text);
}
